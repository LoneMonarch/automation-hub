"""Module API v1: modules return evidence, host owns durable state."""
from dataclasses import dataclass
from typing import Protocol


@dataclass
class Result:
    state: str
    remote_id: str = ''
    verification: str = ''
    error: str = ''


class Module(Protocol):
    def describe_settings(self) -> list[dict]: ...
    def validate(self, path: str) -> str: ...
    def preview(self, path: str, settings: dict) -> str: ...
    def open(self, settings: dict, credentials: dict): ...
    def prepare(self, job: dict) -> tuple[str, dict]: ...
    def submit(self, job: dict) -> Result: ...
    def reconcile(self, job: dict) -> Result: ...
    def close(self): ...
